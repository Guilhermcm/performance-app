// Builds supabase/release/0007-0016_nutrition.sql: migrations 0007 to 0016 in order, in one file,
// for a production database that already has 0001 to 0006 (see docs/SETUP.md). Generated; edit the
// migrations and run `node scripts/build-release-sql.mjs` again instead of editing the bundle.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const MIGRATIONS = join(root, 'supabase', 'migrations')
export const OUT = join(root, 'supabase', 'release', '0007-0016_nutrition.sql')
const FIRST = 7
const LAST = 16

export function releaseFiles() {
  return readdirSync(MIGRATIONS)
    .filter(f => /^\d{4}_.*\.sql$/.test(f))
    .filter(f => { const n = Number(f.slice(0, 4)); return n >= FIRST && n <= LAST })
    .sort()
}

export function buildReleaseSql() {
  const files = releaseFiles()
  const header = [
    '-- performance-app: migrations 0007 to 0016 (Nutrition, phases 2a and 2b) in one file.',
    '-- GENERATED by scripts/build-release-sql.mjs. Do not edit; edit the migrations instead.',
    '-- Run once, whole, in the Supabase SQL Editor, on a database that already has 0001 to 0006.',
    `-- Files: ${files.join(', ')}`,
    ''
  ].join('\n')
  const parts = files.map(f => `-- ===== ${f} =====\n${readFileSync(join(MIGRATIONS, f), 'utf8').trimEnd()}\n`)
  return `${header}\n${parts.join('\n')}`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, buildReleaseSql())
  console.log(`wrote ${OUT} (${releaseFiles().length} migrations)`)
}
