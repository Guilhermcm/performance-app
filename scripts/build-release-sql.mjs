// Builds the release bundles in supabase/release/: named ranges of migrations, in order, in one file
// each, for a production database that is already at the migration before the range (see
// docs/SETUP.md). Generated; edit the migrations and run `node scripts/build-release-sql.mjs`
// again instead of editing a bundle.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const MIGRATIONS = join(root, 'supabase', 'migrations')
const RELEASE = join(root, 'supabase', 'release')

export const RELEASES = [
  {
    name: '0007-0016_nutrition',
    first: 7,
    last: 16,
    title: 'migrations 0007 to 0016 (Nutrition, phases 2a and 2b)',
    needs: '0001 to 0006'
  },
  {
    name: '0017-0020_checkin',
    first: 17,
    last: 20,
    title: 'migrations 0017 to 0020 (photo check-in and social, phase 1c)',
    needs: '0001 to 0016'
  },
  {
    name: '0021-0025_sleep',
    first: 21,
    last: 25,
    title: 'migrations 0021 to 0025 (Sleep, phase 3)',
    needs: '0001 to 0020'
  },
  {
    name: '0026-0030_habits',
    first: 26,
    last: 30,
    title: 'migrations 0026 to 0030 (Habits, phase 4a)',
    needs: '0001 to 0025'
  }
].map(r => ({ ...r, out: join(RELEASE, `${r.name}.sql`) }))

export function releaseFiles(release) {
  return readdirSync(MIGRATIONS)
    .filter(f => /^\d{4}_.*\.sql$/.test(f))
    .filter(f => { const n = Number(f.slice(0, 4)); return n >= release.first && n <= release.last })
    .sort()
}

export function buildReleaseSql(release) {
  const files = releaseFiles(release)
  const header = [
    `-- performance-app: ${release.title} in one file.`,
    '-- GENERATED by scripts/build-release-sql.mjs. Do not edit; edit the migrations instead.',
    `-- Run once, whole, in the Supabase SQL Editor, on a database that already has ${release.needs}.`,
    `-- Files: ${files.join(', ')}`,
    ''
  ].join('\n')
  const parts = files.map(f => `-- ===== ${f} =====\n${readFileSync(join(MIGRATIONS, f), 'utf8').trimEnd()}\n`)
  return `${header}\n${parts.join('\n')}`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(RELEASE, { recursive: true })
  for (const release of RELEASES) {
    writeFileSync(release.out, buildReleaseSql(release))
    console.log(`wrote ${release.out} (${releaseFiles(release).length} migrations)`)
  }
}
